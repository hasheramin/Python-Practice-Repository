# A Program to import and use a Python module

import math

number = 25

print("Square root:", math.sqrt(number))
print("Value of pi:", math.pi)

# Explanation:
# First, the math module is imported using import math.
# The sqrt() function is accessed through math.sqrt().
# The pi constant is accessed through math.pi.
# Modules allow us to reuse functionality without writing it ourselves.

# Real-Life Use:
# Modules are commonly used for mathematics, file handling, dates, networking, data processing, and many other tasks.