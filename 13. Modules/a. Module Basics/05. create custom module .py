# A Program to import and use a custom module for greetings

import greetings

greetings.greet("Hasher")
greetings.welcome("Python Learner")

# Explanation:
# greetings.py is our own custom module.
# The main program imports that module using import greetings.
# Its functions are then accessed using greetings.function_name().
# Python allows us to divide large programs into separate modules.

# Real-Life Use:
# Custom modules help organize large applications into smaller and reusable files.