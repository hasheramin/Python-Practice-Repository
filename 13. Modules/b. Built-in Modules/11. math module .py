# A Program to use mathematical functions from the math module

import math

number = 16

print("Square root:", math.sqrt(number))
print("Power:", math.pow(2, 5))
print("Ceiling:", math.ceil(4.3))
print("Floor:", math.floor(4.8))

# Explanation:
# The math module provides ready-to-use mathematical functions.
# sqrt() calculates the square root of a number.
# pow() calculates a number raised to a power.
# ceil() rounds a number upward.
# floor() rounds a number downward.

