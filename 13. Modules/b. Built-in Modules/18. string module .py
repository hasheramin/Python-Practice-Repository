# A Program to use constants from the string module

import string

print("Lowercase letters:")
print(string.ascii_lowercase)

print("\nUppercase letters:")
print(string.ascii_uppercase)

print("\nDigits:")
print(string.digits)

print("\nPunctuation:")
print(string.punctuation)

# Explanation:
# The string module provides useful constants related to text.
# ascii_lowercase contains lowercase English letters.
# ascii_uppercase contains uppercase English letters.
# digits contains numeric characters.
# punctuation contains common punctuation characters.

# Real-Life Use:
# These constants can be useful for password generation, text validation, character filtering, and input processing.