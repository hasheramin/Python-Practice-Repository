# A Program to display a monthly calendar

import calendar

year = 2026
month = 9

print("\n",calendar.month(year, month))

# Explanation:
# The calendar module provides functions for working with calendars.
# calendar.month() generates a formatted calendar for a given month. We provide the year and month as arguments.

# Real-Life Use:
# Calendar functionality can be used in scheduling applications, appointment systems, planning tools, and date-based reports.